# ----------------------------------------------------------------------------- table 4: agreement
def tex_agreement(rows, A):
    n = len(rows)
    L, V = A["lens"], A["vector"]
    f2 = lambda x: "%.2f" % x
    # the displayed components must reproduce the displayed kappa; if not, show three decimals
    nd = 2
    for S in (L, V):
        shown = (round(S["po"], 2) - round(S["pe"], 2)) / (1 - round(S["pe"], 2))
        if "%.2f" % shown != "%.2f" % S["kappa"]:
            nd = 3
    fc = lambda x: ("%." + str(nd) + "f") % x
    stat = []
    for name, S in (("Lens", L), ("Vector", V)):
        stat.append(" & ".join([name, str(S["k"]), "%d/%d (%s\\%%)" % (S["agree"], S["n"], pct(S["agree"], S["n"])),
                                fc(S["po"]), fc(S["pe"]), f2(S["kappa"])]) + r" \\")
    # lens confusion matrix, coding 1 in rows, coding 2 in columns
    conf = A["conf"]
    cm = []
    for l1 in LENSES:
        cells = [l1]
        for l2 in LENSES:
            v = conf[(l1, l2)]
            cells.append(r"\textbf{%d}" % v if l1 == l2 else str(v))
        cells.append(str(sum(conf[(l1, l2)] for l2 in LENSES)))
        cm.append(" & ".join(cells) + r" \\")
    coltot = [str(sum(conf[(l1, l2)] for l1 in LENSES)) for l2 in LENSES]
    cm_total = " & ".join(["Total"] + coltot + [str(n)]) + r" \\"
    dis = []
    for r in A["lens_dis"]:
        dis.append(" & ".join([r"\mbox{%s}" % r["did"], esc(r["name"]), r["lens"], r["lens2"]]) + r" \\")
    cap = T(r"Agreement between the first coding and the blind second coding of the lens and vector fields of all "
            r"<<n>> events. $\kappa=(p_o-p_e)/(1-p_e)$, where $p_o$ is the observed agreement and "
            r"$p_e=\sum_k p_{1k}p_{2k}$ the agreement expected from the two codings' marginals; lens: "
            r"$(<<lpo>>-<<lpe>>)/(1-<<lpe>>)=<<lk>>$, vector: $(<<vpo>>-<<vpe>>)/(1-<<vpe>>)=<<vk>>$. "
            r"The <<m>> lens disagreements were adjudicated in favour of the first coding.",
            n=n, lpo=fc(L["po"]), lpe=fc(L["pe"]), lk=f2(L["kappa"]),
            vpo=fc(V["po"]), vpe=fc(V["pe"]), vk=f2(V["kappa"]), m=len(A["lens_dis"]))
    W = r">{\raggedright\arraybackslash}p{\dimexpr0.52\linewidth\relax}"
    return HEADER + "\n".join([
        r"\begin{table}[%s]" % FLOAT_POS,
        r"\centering\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\caption{%s}" % cap,
        r"\label{tab:ds-agreement}",
        r"\textit{(a) Per field}\par\smallskip",
        r"{\setlength{\tabcolsep}{7pt}",
        r"\begin{tabular}{@{}lrrrrr@{}}",
        r"\toprule",
        r"Field & Categories & Agreed & $p_o$ & $p_e$ & $\kappa$ \\",
        r"\midrule", *stat, r"\bottomrule",
        r"\end{tabular}}",
        r"\par\medskip",
        r"\textit{(b) Lens, first coding (rows) against second coding (columns)}\par\smallskip",
        r"{\setlength{\tabcolsep}{7pt}",
        r"\begin{tabular}{@{}lrrrr@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Second coding} & \\",
        r"\cmidrule(lr){2-4}",
        r"First coding & " + " & ".join(LENSES) + r" & Total \\",
        r"\midrule", *cm, r"\midrule", cm_total, r"\bottomrule",
        r"\end{tabular}}",
        r"\par\medskip",
        r"\textit{(c) The %d lens disagreements}\par\smallskip" % len(A["lens_dis"]),
        r"\begin{tabular}{@{}l%s ll@{}}" % W,
        r"\toprule",
        r"ID & Event & First coding & Second coding \\",
        r"\midrule", *dis, r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}", ""])


