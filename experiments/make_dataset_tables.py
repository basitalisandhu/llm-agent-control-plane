def figure_target(name=None):
    """Never overwrite a figure this script did not write (another generator may own the name)."""
    if name:
        return TEX / name
    t = TEX / FIG_NAME
    if t.exists() and FIG_TAG not in t.read_bytes():
        print("NOTICE: tex/%s exists and was not written by this script; writing tex/%s instead (use --fig-name to "
              "choose a name)" % (FIG_NAME, FIG_ALT), file=sys.stderr)
        return TEX / FIG_ALT
    return t


