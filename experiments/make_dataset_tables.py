def tex_codebook(rows):
    n = len(rows)
    warnings = []
    first, last = min(r["date"] for r in rows), max(r["date"] for r in rows)
    collection = T(
        r"\paragraph{Collection.} The dataset records <<n>> events (<<ninc>> incidents, <<ndis>> vulnerability "
        r"disclosures and <<nthr>> threat reports), dated <<first>> to <<last>>, that involve an LLM-based system or an "
        r"attacker's operational use of generative AI. Candidates were found in <<k>> kinds of public source: <<src>>; "
        r"each event carries one primary source, which was opened and read to code it. There was no search protocol "
        r"beyond naming these source types, and no census was kept of the candidates that were considered and "
        r"excluded. The dataset is therefore a convenience sample of what was public, not a census: it over-represents "
        r"what vendors and researchers chose to disclose, and no count or share computed from it estimates a share of "
        r"any population.",
        n=n, ninc=cnt(rows, type="incident"), ndis=cnt(rows, type="vulnerability-disclosure"),
        nthr=cnt(rows, type="threat-report"), first=month_name(first), last=month_name(last),
        k=word(len(SOURCE_TYPES)), src=", ".join(SOURCE_TYPES[:-1]) + " and " + SOURCE_TYPES[-1])
    declared = [f for f, _ in RECORD_FIELDS] + [f for f, _, _ in CODEBOOK]
    if sorted(declared) != sorted(CSV_FIELDS):
        warnings.append("codebook fields %s differ from the CSV columns %s" % (declared, CSV_FIELDS))
    fields_par = T(r"\paragraph{Fields.} Each event is one row of <<nf>> fields: <<nr>> identify the event and <<nc>> are "
                   r"coded and used in the analysis. The rules below are applied to the primary source of the event; the "
                   r"number in parentheses after a value is the number of events that carry it.",
                   nf=word(len(CSV_FIELDS)), nr=word(len(RECORD_FIELDS)), nc=word(len(CODEBOOK)))
    out = [HEADER.rstrip("\n"),
           r"\providecommand{\cbval}[1]{{\normalfont\ttfamily #1}}",
           r"\providecommand{\cbn}[1]{{\normalfont\footnotesize (#1)}}",
           collection, "",
           fields_par,
           r"\begingroup\footnotesize\emergencystretch=3em",
           r"\paragraph{Identifying fields.}",
           r"\begin{description}"]
    for f, rule in RECORD_FIELDS:
        out.append(r"\item[\cbval{%s}] %s" % (esc(f), rule))
    out += [r"\end{description}",
            r"\paragraph{Coded fields.}",
            r"\begin{description}"]
    for field, intro, values in CODEBOOK:
        present = collections.Counter(r[field] for r in rows)
        known = {v for v, _ in values}
        for v in present:
            if v not in known:
                warnings.append("codebook has no rule for %s = %r (in the data)" % (field, v))
        out.append(r"\item[\cbval{%s}] %s" % (esc(field), intro))
        out.append(r"\begin{description}")
        for v, rule in values:
            nv = present.get(v, 0)
            if nv == 0:
                warnings.append("codebook rule for %s = %r, which is absent from the data" % (field, v))
            ex = ""
            if field in EXAMPLE_FIELDS and nv:
                ex = r" (e.g.\ %s)" % did_tex(sel(rows, **{field: v})[:2])
            out.append(r"\item[\cbval{%s} \cbn{%d}] %s%s" % (esc(v), nv, rule, ex))
        for v in sorted(set(present) - known):     # never drop a value silently
            out.append(r"\item[\cbval{%s} \cbn{%d}] \textbf{TODO: no rule written for this value.}" % (esc(v), present[v]))
        if field == "lens":
            chat = sel(rows, lens="surface", authority="none", vector={"direct-injection", "jailbreak", "excessive-agency"})
            flaws = sel(rows, lens="target", vector="exploitation")
            out.append(r"\item[\emph{tie-break}] AI as conduit to another party's assets is \cbval{surface}; AI as the "
                       r"attacker's instrument is \cbval{weapon}; otherwise \cbval{target}. Cases decided under it: "
                       r"chatbot output that harms its deployer without any tool authority is \cbval{surface} (%s); a "
                       r"flaw in an AI product's own code or configuration, exploited without the model's obedience "
                       r"to injected content, is \cbval{target} (%s). The events on which a second coding differed "
                       r"are listed in the agreement table." % (did_tex(chat), did_tex(flaws)))
        out.append(r"\end{description}")
    out += [r"\end{description}", r"\endgroup", ""]
    for w in warnings:
        print("WARNING:", w, file=sys.stderr)
    return "\n".join(out)


