def load():
    global CSV_FIELDS
    reader = csv.DictReader(open(SRC1, newline="", encoding="utf-8"))
    CSV_FIELDS = list(reader.fieldnames)
    rows = list(reader)
    c2 = {r["id"]: r for r in csv.DictReader(open(SRC2, newline="", encoding="utf-8"))}
    ids = [r["id"] for r in rows]
    assert len(set(ids)) == len(ids), "duplicate ids in incidents.csv"
    assert set(ids) == set(c2), "incidents_coder2.csv does not cover exactly the ids of incidents.csv"
    for r in rows:
        r["n"] = int(r["id"])
        r["did"] = "D-%d" % r["n"]
        r["year"] = int(r["date"][:4])
        r["month"] = int(r["date"][5:7])
        r["q"] = (r["year"], (r["month"] - 1) // 3 + 1)
        r["lens2"] = c2[r["id"]]["lens"]
        r["vector2"] = c2[r["id"]]["vector"]
    assert all(r["lens"] in LENSES and r["lens2"] in LENSES for r in rows), "unexpected lens value"
    assert all(r["type"] in TYPES for r in rows), "unexpected type value"
    return rows


def sel(rows, **kw):
    out = rows
    for k, v in kw.items():
        if isinstance(v, (set, frozenset, list)):
            out = [r for r in out if r[k] in v]
        else:
            out = [r for r in out if r[k] == v]
    return out


def cnt(rows, **kw):
    return len(sel(rows, **kw))


_SPECIAL = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
            "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}


def esc(s):
    """LaTeX-escape a CSV string; straight double quotes become typographic ones."""
    s = re.sub(r'"([^"]*)"', r"``\1''", s)
    return "".join(_SPECIAL.get(c, c) for c in s)


def T(s, **kw):
    """Fill <<name>> markers (so LaTeX braces need no doubling)."""
    for k, v in kw.items():
        s = s.replace("<<%s>>" % k, str(v))
    assert "<<" not in s, "unfilled marker in template"
    return s


def did_tex(rs):
    return ", ".join(r"\mbox{%s}" % r["did"] for r in rs)


def did_md(rs):
    return ", ".join(r["did"] for r in rs) if rs else "none"


def ev(k):
    return "%d event%s" % (k, "" if k == 1 else "s")


def pct(a, b, nd=1):
    """Percentage as a string, rounded half up (81.25 -> 81.3), via exact decimal arithmetic."""
    from decimal import Decimal, ROUND_HALF_UP
    q = Decimal(1).scaleb(-nd)
    return str((Decimal(100) * Decimal(a) / Decimal(b)).quantize(q, rounding=ROUND_HALF_UP))


def month_name(ym):
    y, m = int(ym[:4]), int(ym[5:7])
    return "%s %d" % (calendar.month_name[m], y)


def quarters(rows):
    qs = sorted({r["q"] for r in rows})
    out, (y, q) = [], qs[0]
    while (y, q) <= qs[-1]:
        out.append((y, q))
        q += 1
        if q == 5:
            y, q = y + 1, 1
    return out


def qlabel(q):
    return "%dQ%d" % q


def ordered_counts(rs, field):
    """Counts of a field, largest first, ties alphabetical, 'none' always last."""
    c = collections.Counter(r[field] for r in rs)
    items = sorted(((k, v) for k, v in c.items() if k != "none"), key=lambda kv: (-kv[1], kv[0]))
    if "none" in c:
        items.append(("none", c["none"]))
    return items


def kappa_stats(a, b):
    n = len(a)
    assert n == len(b) and n > 0
    agree = sum(1 for x, y in zip(a, b) if x == y)
    po = agree / n
    ca, cb = collections.Counter(a), collections.Counter(b)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / (n * n)
    kappa = (po - pe) / (1 - pe)
    return dict(n=n, agree=agree, po=po, pe=pe, kappa=kappa, k=len(set(a) | set(b)),
                k1=len(set(a)), k2=len(set(b)))


def agreement(rows):
    A = {"lens": kappa_stats([r["lens"] for r in rows], [r["lens2"] for r in rows]),
         "vector": kappa_stats([r["vector"] for r in rows], [r["vector2"] for r in rows])}
    A["conf"] = {(l1, l2): cnt(rows, lens=l1, lens2=l2) for l1 in LENSES for l2 in LENSES}
    A["lens_dis"] = [r for r in rows if r["lens"] != r["lens2"]]
    A["vec_dis"] = [r for r in rows if r["vector"] != r["vector2"]]
    return A


def coverage(rows):
    surf = sel(rows, lens="surface")
    adv, noadv = sel(surf, adversarial="yes"), sel(surf, adversarial="no")
    classes, assigned = [], set()
    for name, chans in COVERAGE_CLASSES:
        members = [r for r in adv if r["channel_out"] in chans]
        assigned |= {r["id"] for r in members}
        classes.append(dict(name=name, channels=chans, rows=members,
                            by_channel=[(c, cnt(members, channel_out=c)) for c in chans]))
    left = [r for r in adv if r["id"] not in assigned]
    if left:   # never drop an event silently
        print("WARNING: adversarial surface events whose channel_out fits no class: %s" % did_md(left), file=sys.stderr)
        chans = sorted({r["channel_out"] for r in left})
        classes.append(dict(name="Unclassified", channels=chans, rows=left,
                            by_channel=[(c, cnt(left, channel_out=c)) for c in chans]))
    assert sum(len(c["rows"]) for c in classes) == len(adv)
    noadv_by = [(c, cnt(noadv, channel_out=c)) for c in sorted({r["channel_out"] for r in noadv})]
    return dict(surf=surf, adv=adv, noadv=noadv, classes=classes, noadv_by=noadv_by)


