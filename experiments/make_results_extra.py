"""Macros for the pilot ablation (approval-only, runs_v2 pep_tiers) and the baseline repeat (runs_v2_rep1)."""
import json, glob, collections, random
from pathlib import Path
SUITES = ["slack", "banking", "travel", "workspace"]
def load(logdir, tag, config):
    S = {}
    for f in glob.glob(f"{logdir}/summaries/{tag}__{config}__*.json"):
        d = json.load(open(f)); S[(d["suite"], d["mode"])] = d
    return S
def agg(S, mode, key):
    cl = collections.defaultdict(list)
    for s in SUITES:
        d = S.get((s, mode))
        if d:
            for k, v in d[key].items(): cl[(s, k.split("|")[0])].append(1 if v else 0)
    flat = [x for c in cl.values() for x in c]
    if not flat: return float("nan"), 0, (float("nan"), float("nan"))
    vals = list(cl.values()); rng = random.Random(0); means = []
    for _ in range(2000):
        fl = [x for c in (rng.choice(vals) for _ in vals) for x in c]; means.append(sum(fl) / len(fl) * 100)
    means.sort(); return sum(flat) / len(flat) * 100, len(flat), (means[50], means[1949])
out = {}
for name, logdir, config in [("Tiers", "runs_v2", "pep_tiers"), ("BaseRep", "runs_v2_rep1", "baseline")]:
    S = load(logdir, "qwen14b", config)
    u, nu, uci = agg(S, "utility", "utility_results"); a, na, aci = agg(S, "security", "security_results"); ua, _, _ = agg(S, "security", "utility_results")
    out[f"asr{name}"] = f"{a:.1f}"; out[f"asrCI{name}"] = f"{a:.1f} [{aci[0]:.0f}, {aci[1]:.0f}]"; out[f"util{name}"] = f"{u:.1f}"; out[f"utilCI{name}"] = f"{u:.1f} [{uci[0]:.0f}, {uci[1]:.0f}]"; out[f"utilAtk{name}"] = f"{ua:.1f}"
    out[f"nU{name}"] = str(nu); out[f"nS{name}"] = str(na)
    per = {s: (S[(s, "security")]["security"] * 100 if (s, "security") in S else None, S[(s, "utility")]["utility"] * 100 if (s, "utility") in S else None) for s in SUITES}
    print(name, "ASR", out[f"asrCI{name}"], "util", out[f"utilCI{name}"], "UA", out[f"utilAtk{name}"], "n", nu, na, "per-suite (asr, util):", per)
with open("tex/results_extra.tex", "w") as f:
    f.write("% auto-generated by make_results_extra.py\n")
    for k, v in out.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print("wrote tex/results_extra.tex")

# ---- local obfuscated-attack runs (runs_v2_obf): ASR per config under the obfuscated attack, strict-variant utility
out2 = {}
for name, config, mode in [("ObfBase", "baseline", "security"), ("ObfProv", "pep_prov", "security"), ("ObfStrict", "pep_prov_strict", "security"), ("StrictA", "pep_prov_strict", "utility")]:
    S = load("runs_v2_obf", "qwen14b", config)
    key = "security_results" if mode == "security" else "utility_results"
    v, n, ci = agg(S, mode, key)
    ua = agg(S, "security", "utility_results")[0] if mode == "security" else float("nan")
    out2[f"asr{name}" if mode == "security" else f"util{name}"] = "--" if v != v else f"{v:.1f}"
    out2[f"asrCI{name}" if mode == "security" else f"utilCI{name}"] = "--" if v != v else f"{v:.1f} [{ci[0]:.0f}, {ci[1]:.0f}]"
    out2[f"n{name}"] = str(n)
    if mode == "security": out2[f"utilAtk{name}"] = "--" if ua != ua else f"{ua:.1f}"
    per = {s: (S[(s, mode)][key.split("_")[0]] * 100 if (s, mode) in S else None) for s in SUITES}
    print(name, out2.get(f"asrCI{name}", out2.get(f"utilCI{name}")), "n", n, per)
with open("tex/results_extra.tex", "a") as f:
    for k, v in out2.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print("appended obf macros")
