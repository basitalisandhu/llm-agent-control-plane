"""Aggregates runs/summaries/*.json into results.tex macros, a per-suite table and fig_results.pdf."""
import json, glob, sys, collections
from pathlib import Path
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt

LOGDIR = Path(sys.argv[1] if len(sys.argv) > 1 else "runs_v2")
TAG = sys.argv[2] if len(sys.argv) > 2 else "qwen14b"
TEX = Path("tex")
CONFIGS = ["baseline", "spotlight", "pep_prov", "pep_full"]
LABELS = {"baseline": "Baseline", "spotlight": "Spotlight", "pep_prov": "PEP-prov", "pep_full": "PEP-full"}
SUITES = ["slack", "banking", "travel", "workspace"]

S = {}
for f in glob.glob(str(LOGDIR / "summaries" / f"{TAG}__*.json")):
    d = json.load(open(f)); S[(d["config"], d["suite"], d["mode"])] = d
# consistency: every config must cover the same (user task, injection task) keys per suite/mode
for suite in SUITES:
    for mode in ["utility", "security"]:
        keysets = {c: set(S[(c, suite, mode)]["utility_results"]) for c in CONFIGS if (c, suite, mode) in S}
        if len({frozenset(v) for v in keysets.values()}) > 1:
            print("WARNING: key sets differ for", suite, mode, {c: len(v) for c, v in keysets.items()})

def agg(config, mode, key):
    vals = []
    for suite in SUITES:
        d = S.get((config, suite, mode))
        if d: vals.extend(d[key].values())
    return (sum(vals) / len(vals) * 100 if vals else float("nan")), len(vals)

rows = {}
for c in CONFIGS:
    util, n_u = agg(c, "utility", "utility_results")
    sec, n_s = agg(c, "security", "security_results")
    util_atk, _ = agg(c, "security", "utility_results")
    rows[c] = dict(util=util, n_u=n_u, asr=sec if n_s else float("nan"), n_s=n_s, util_atk=util_atk)

def fmt(x): return "--" if x != x else f"{x:.1f}"

def wilson(k, n, z=1.96):
    """Wilson score interval for a proportion, returned in percent."""
    if n == 0: return (float("nan"), float("nan"))
    p = k / n; d = 1 + z * z / n; c = p + z * z / (2 * n); h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5)
    return ((c - h) / d * 100, (c + h) / d * 100)

import random
def cluster_ci(config, mode, key, iters=2000, seed=0):
    """Bootstrap by user task (cases of one user task are resampled together); returns (lo, hi) in percent."""
    clusters = collections.defaultdict(list)
    for suite in SUITES:
        d = S.get((config, suite, mode))
        if not d: continue
        for k, v in d[key].items(): clusters[(suite, k.split("|")[0])].append(1 if v else 0)
    cl = list(clusters.values())
    if not cl: return (float("nan"), float("nan"))
    rng = random.Random(seed); means = []
    for _ in range(iters):
        sample = [rng.choice(cl) for _ in cl]; flat = [x for c in sample for x in c]
        means.append(sum(flat) / len(flat) * 100)
    means.sort(); return (means[int(0.025 * iters)], means[int(0.975 * iters) - 1])

def ci_str(pct, n, config=None, mode=None, key=None):
    if pct != pct or n == 0: return "--"
    lo, hi = cluster_ci(config, mode, key) if config else wilson(round(pct / 100 * n), n)
    return f"{pct:.1f} [{lo:.0f}, {hi:.0f}]"
macros = {
    "asrBase": fmt(rows["baseline"]["asr"]), "asrSpot": fmt(rows["spotlight"]["asr"]), "asrProv": fmt(rows["pep_prov"]["asr"]), "asrFull": fmt(rows["pep_full"]["asr"]),
    "utilBase": fmt(rows["baseline"]["util"]), "utilSpot": fmt(rows["spotlight"]["util"]), "utilProv": fmt(rows["pep_prov"]["util"]), "utilFull": fmt(rows["pep_full"]["util"]),
    "utilAtkBase": fmt(rows["baseline"]["util_atk"]), "utilAtkSpot": fmt(rows["spotlight"]["util_atk"]), "utilAtkProv": fmt(rows["pep_prov"]["util_atk"]), "utilAtkFull": fmt(rows["pep_full"]["util_atk"]),
    "nUserTasks": str(rows["baseline"]["n_u"]), "nPairs": str(rows["baseline"]["n_s"]), "nInjTasks": "8",
}
for c, key in [("baseline", "Base"), ("spotlight", "Spot"), ("pep_prov", "Prov"), ("pep_full", "Full")]:
    macros[f"asrCI{key}"] = ci_str(rows[c]["asr"], rows[c]["n_s"], c, "security", "security_results")
    macros[f"utilCI{key}"] = ci_str(rows[c]["util"], rows[c]["n_u"], c, "utility", "utility_results")
    macros[f"utilAtkCI{key}"] = ci_str(rows[c]["util_atk"], rows[c]["n_s"], c, "security", "utility_results")
# incident macros are written by make_incidents.py into results_incidents.tex; keep them if present
inc = ''
with open(TEX / "results.tex", "w") as f:
    f.write("% auto-generated by make_results.py\n" + inc)
    for k, v in macros.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    f.write("\\newcommand{\\modelName}{Qwen2.5-14B-Instruct}\n")

# per-suite table
with open(TEX / "table_suites.tex", "w") as f:
    f.write("\\begin{tabular}{@{}l" + "rr" * len(SUITES) + "@{}}\n\\toprule\n")
    f.write("Configuration & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{s.capitalize()}}}" for s in SUITES) + " \\\\\n")
    f.write(" & " + " & ".join("ASR & Util" for _ in SUITES) + " \\\\\n\\midrule\n")
    for c in CONFIGS:
        cells = []
        for s in SUITES:
            ds, du = S.get((c, s, "security")), S.get((c, s, "utility"))
            asr = fmt(ds["security"] * 100) if ds else "--"
            ut = fmt(du["utility"] * 100) if du else "--"
            cells.append(f"{asr} & {ut}")
        f.write(f"\\textsc{{{LABELS[c]}}} & " + " & ".join(cells) + " \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

# figure
fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.3))
import numpy as np
x = np.arange(len(SUITES)); w = 0.2
greys = ["#9e9e9e", "#6f6f6f", "#2c7fb8", "#0b3d91"]
for i, c in enumerate(CONFIGS):
    asr = [S[(c, s, "security")]["security"] * 100 if (c, s, "security") in S else 0 for s in SUITES]
    ut = [S[(c, s, "utility")]["utility"] * 100 if (c, s, "utility") in S else 0 for s in SUITES]
    axes[0].bar(x + (i - 1.5) * w, asr, w, label=LABELS[c], color=greys[i])
    axes[1].bar(x + (i - 1.5) * w, ut, w, label=LABELS[c], color=greys[i])
for ax, title in zip(axes, ["Targeted attack success rate (%)", "Benign utility (%)"]):
    ax.set_xticks(x); ax.set_xticklabels([s.capitalize() for s in SUITES], fontsize=8); ax.set_title(title, fontsize=9)
    ax.set_ylim(0, 100); ax.tick_params(axis="y", labelsize=8); ax.spines[["top", "right"]].set_visible(False)
axes[0].legend(fontsize=7, frameon=False, ncol=2)
fig.tight_layout(); fig.savefig(TEX / "fig_results.pdf"); print("wrote results.tex, table_suites.tex, fig_results.pdf")
for c in CONFIGS: print(c, {k: (round(v, 1) if isinstance(v, float) else v) for k, v in rows[c].items()})
