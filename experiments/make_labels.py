"""Writes tex/labels_supp.tex and tex/labels_main.tex: the cross-document labels of the IEEE supplement/main as \\newlabel lines
with the S-/M- prefixes xr would use, so either document compiles standalone (e.g. on Overleaf) without the other's .aux file."""
import re, os
TEX=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tex')
def labels(aux, prefix, out):
    s=open(os.path.join(TEX, aux), errors='ignore').read()
    lines=[]
    for m in re.finditer(r'^\\newlabel\{([^}]+)\}(\{.*\})\s*$', s, flags=re.M):
        lines.append('\\newlabel{%s%s}%s' % (prefix, m.group(1), m.group(2)))
    open(os.path.join(TEX, out), 'w').write('%% auto-generated by make_labels.py from %s; lets the other IEEE document resolve its cross-references without this .aux file\n' % aux + '\n'.join(lines) + '\n')
    return len(lines)
print('labels_supp.tex:', labels('paper_tdsc_supp.aux', 'S-', 'labels_supp.tex'), '| labels_main.tex:', labels('paper_tdsc.aux', 'M-', 'labels_main.tex'))
